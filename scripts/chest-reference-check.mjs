import {loadPlaywright} from './playwright-runtime.mjs';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {EXAMPLE_SCENE} from '../app/src/scene-format.js';
const out='validation/chest-reference';await mkdir(out,{recursive:true});
const {chromium}=loadPlaywright();
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=d3d11']});
const page=await browser.newPage({viewport:{width:1600,height:1100},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
async function download(selector,name,json=true){const pending=page.waitForEvent('download');await page.locator(selector).click();const d=await pending;const file=out+'/'+name;await d.saveAs(file);const bytes=await readFile(file);return json?JSON.parse(bytes):bytes;}
const save=name=>download('#btn-save',name);
try{
  await page.goto('http://127.0.0.1:3002');await page.waitForSelector('#body-height');
  const engine=await page.evaluate(async()=>{
    const rig=await import('/src/body-rig.js');
    const urls=performance.getEntriesByType('resource').map(e=>e.name);
    const THREE=await import(urls.find(u=>/\.vite\/deps\/three\.js/.test(u)));
    const m=rig.createCharacter({height:1.65,headUnits:8,chest:{height:0.65,spacing:0.46,projection:1}});
    const group=m.getObjectByName('Chest volume reference'),positions=group.children.map(mesh=>mesh.position.toArray()),lengths=rig.boneDistances(m);
    const before=rig.chestLandmarks(m);m.torso.bend=40;m.torso.turn=25;rig.constrainBody(m);
    const posed=rig.chestLandmarks(m);
    if(JSON.stringify(before.left)===JSON.stringify(posed.left))throw Error('Chest did not follow torso');
    if(JSON.stringify(positions)!==JSON.stringify(group.children.map(mesh=>mesh.position.toArray())))throw Error('Chest local anchors changed');
    const drift=Math.max(...Object.entries(rig.boneDistances(m)).map(([key,value])=>Math.abs(value-lengths[key])));
    if(drift>1e-6)throw Error('Chest posing stretched bones');
    group.children[0].position.y+=50;rig.constrainBody(m);
    if(group.children[0].position.y!==positions[0][1])throw Error('Chest anchor not locked');
    rig.configureBody(m,{height:1.65,headUnits:9.5,chest:{height:0.72,spacing:0.5,projection:1.2}});
    if(rig.chestLandmarks(m)===null||group.children[0].position.y!==17*0.72)throw Error('Chest resize failed');
    const heightError=Math.abs(m.userData.bodyMetrics.height-1.65),ratioError=Math.abs(m.userData.bodyMetrics.headUnits-9.5);
    if(heightError>1e-6||ratioError>1e-6)throw Error('Chest changed stature/head ratio');
    rig.configureBody(m,{height:1.65,headUnits:9.5});
    if(rig.chestLandmarks(m)!==null||m.getObjectByName('Chest volume reference'))throw Error('Chest toggle removal failed');
    m.parent.remove(m);return {torsoFollow:true,localAnchorsLocked:true,boneDrift:drift,heightError,ratioError,toggleRemoval:true};
  });checks.push('torso-following local anchors, length lock, height/head ratio and removal');
  await page.goto('http://127.0.0.1:3001');await page.locator('#studio-example').click();
  await page.locator('.layer-item[data-imported="false"][data-idx="1"] span').first().click();
  await page.getByText('가슴 형태 참조',{exact:true}).click();await page.locator('#body-chest-enabled').check();
  await page.locator('#body-chest-height').fill('70');await page.locator('#body-apply').click();
  const configured=await save('configured.json');
  assert.equal(configured.mannequins[0].bodyProfile.chest,undefined);
  assert.deepEqual(configured.mannequins[1].bodyProfile.chest,{height:0.7,spacing:0.46,projection:1});checks.push('independent per-actor chest controls');
  await page.locator('#btn-undo').click();assert.equal(await page.locator('#body-chest-enabled').isChecked(),false);
  await page.locator('#btn-redo').click();assert.equal(await page.locator('#body-chest-enabled').isChecked(),true);
  await page.locator('#btn-load').setInputFiles(out+'/configured.json');
  await page.waitForFunction(()=>document.querySelector('#body-chest-enabled')?.checked===true);
  const restored=await save('restored.json');assert.deepEqual(restored.mannequins[1].bodyProfile.chest,configured.mannequins[1].bodyProfile.chest);checks.push('Undo/Redo and save reload');
  await page.locator('#btn-add-mannequin').click();const chooser=page.waitForEvent('filechooser');await page.locator('#btn-add-mannequin-path').click();
  await (await chooser).setFiles({name:'chest-object.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...configured.mannequins[1],type:'mannequin'}))});
  await page.waitForFunction(()=>document.querySelectorAll('.layer-item[data-imported="false"]').length===3);
  const added=await save('added-object.json');assert.deepEqual(added.mannequins[2].bodyProfile.chest,configured.mannequins[1].bodyProfile.chest);checks.push('single-character From File preserves chest');
  const scene=structuredClone(EXAMPLE_SCENE);scene.title='흉곽과 가슴 위치 참조';scene.room.walls=false;scene.props=[];
  scene.actors=[{...scene.actors[1],position:[0,0,0],yaw:0,height:1.65,headUnits:8,chest:{height:0.65,spacing:0.46,projection:1}}];
  scene.camera={position:[2.5,1.4,3],target:[0,1.05,0],fov:32};scene.shots=[{id:'front',name:'사선 체형 참조',camera:scene.camera}];
  await page.locator('#studio-file').setInputFiles({name:'chest-scene.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(scene))});
  await page.waitForFunction(()=>document.querySelector('#studio-status').textContent.includes('인물 1명'));
  const packet=await download('#studio-packet','handoff.json');
  assert.equal(packet.anatomyReferences.length,1);const chest=packet.anatomyReferences[0].chest;
  assert.equal(packet.anatomyReferences[0].actorIndex,0);
  for(const side of ['leftImage','rightImage'])assert.equal(chest[side].inFrame,true);
  await download('#studio-color','color.png',false);await download('#studio-depth','depth.png',false);
  assert.ok(Math.abs(chest.leftImage.point[0]-chest.rightImage.point[0])>0.02,'Front camera should separate chest anchors');
  await page.screenshot({path:out+'/editor.png'});
  const noChest=structuredClone(scene);delete noChest.actors[0].chest;
  await page.locator('#studio-file').setInputFiles({name:'no-chest.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(noChest))});
  await page.waitForFunction(()=>document.querySelector('#studio-validation-source').textContent.includes('no-chest.json'));
  const noPacket=await download('#studio-packet','without-chest.json');assert.equal(noPacket.anatomyReferences.length,0);
  assert.notEqual(packet.images.color,noPacket.images.color);assert.notEqual(packet.images.depth,noPacket.images.depth);checks.push('visible color/depth geometry and camera-projected chest anchors in handoff');
  assert.deepEqual(errors,[]);const report={passed:true,engine,checks,anatomyReferences:packet.anatomyReferences,pageErrors:errors};await writeFile(out+'/report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
